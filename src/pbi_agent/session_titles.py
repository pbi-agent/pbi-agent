"""Local session titles from a small on-device model.

A background task downloads the oot-oneliner GGUF model and the official
prebuilt llama.cpp build for this platform into ``~/.pbi-agent/title-model``.
Once both are present, each title is generated by one short-lived
``llama-completion`` process. Until then, and on any failure, callers keep the
title they already have.
"""

from __future__ import annotations

import logging
import os
import platform
import subprocess
import tempfile
import threading
from pathlib import Path

from pbi_agent.local_assets import Asset, claim, download, extract, machine

_log = logging.getLogger(__name__)

ENABLED_ENV = "PBI_AGENT_LOCAL_TITLES"
ROOT_ENV = "PBI_AGENT_TITLE_MODEL_DIR"

MAX_TITLE_CHARS = 80
# The model was trained on inputs up to roughly 2K tokens.
MAX_INPUT_CHARS = 6000
_CONTEXT_TOKENS = 4096
_MAX_NEW_TOKENS = 32
_GENERATE_TIMEOUT_SECS = 120
_END_MARKER = "[end of text]"


MODEL = Asset(
    url=(
        "https://huggingface.co/oot-ai/oot-oneliner-GGUF/resolve/"
        "e853ae677dece5a141608a964f83ca247a91566c/oot-oneliner-Q4_K_M.gguf"
    ),
    sha256="02fca7b62f303f8744b8fb01271de095ab2ce3cc8699d46a237fce43bf797eec",
    size=1_099_615_456,
)

LLAMA_CPP_TAG = "b12320"
_RELEASE_URL = (
    "https://github.com/ggml-org/llama.cpp/releases/download/"
    f"{LLAMA_CPP_TAG}/llama-{LLAMA_CPP_TAG}-bin-"
)
# (platform.system(), normalized machine) -> official llama.cpp CPU build.
_RUNTIMES: dict[tuple[str, str], Asset] = {
    ("Linux", "x64"): Asset(
        _RELEASE_URL + "ubuntu-x64.tar.gz",
        "66e2c8509052c191fddc4c13c846c7388c07fce519c6b42f8496daf1cf14a793",
        23_311_141,
    ),
    ("Linux", "arm64"): Asset(
        _RELEASE_URL + "ubuntu-arm64.tar.gz",
        "8702f0fab173b2292c24fb274b32992a2767d24a942accc7590ab2c0f77c0a2d",
        18_952_330,
    ),
    ("Darwin", "arm64"): Asset(
        _RELEASE_URL + "macos-arm64.tar.gz",
        "b83dad7c9202b40e4f00405c55a116d50b3b995093b5dbe1262ecd518d039ee0",
        16_896_039,
    ),
    ("Darwin", "x64"): Asset(
        _RELEASE_URL + "macos-x64.tar.gz",
        "d73c4533238196a9edd062f403e40af527dee92f6568a7b1a5219f04f3776135",
        12_639_485,
    ),
    ("Windows", "x64"): Asset(
        _RELEASE_URL + "win-cpu-x64.zip",
        "08b6659fc40ba62a8d07c886d6bc873d00735b1411776507eed18a41f336ab35",
        25_084_274,
    ),
    ("Windows", "arm64"): Asset(
        _RELEASE_URL + "win-cpu-arm64.zip",
        "adda24c474433009c11212aea246c7437dc754e9dd4fca17d42a056d31cc00db",
        13_434_411,
    ),
}

_ensure_lock = threading.Lock()
_generate_lock = threading.Lock()


def enabled() -> bool:
    value = os.environ.get(ENABLED_ENV, "1").strip().lower()
    return value not in {"0", "false", "no", "off"}


def assets_root() -> Path:
    override = os.environ.get(ROOT_ENV)
    if override:
        return Path(override)
    return Path.home() / ".pbi-agent" / "title-model"


def model_path() -> Path:
    return assets_root() / "oot-oneliner-Q4_K_M.gguf"


def runtime_dir() -> Path:
    return assets_root() / f"llama.cpp-{LLAMA_CPP_TAG}"


def runtime_asset() -> Asset | None:
    return _RUNTIMES.get((platform.system(), machine() or ""))


def binary_path() -> Path | None:
    name = "llama-completion.exe" if os.name == "nt" else "llama-completion"
    directory = runtime_dir()
    if not directory.is_dir():
        return None
    return next(iter(sorted(directory.rglob(name))), None)


def is_ready() -> bool:
    """True when titles can be generated right now. Files only appear under
    their final names after their checksum was verified."""
    return enabled() and model_path().is_file() and binary_path() is not None


def ensure_assets() -> None:
    """Download whatever is missing. Blocking; run it off the event loop."""
    if not enabled() or is_ready():
        return
    runtime = runtime_asset()
    if runtime is None:
        _log.info("Local session titles: no llama.cpp build for this platform.")
        return
    if not _ensure_lock.acquire(blocking=False):
        return
    try:
        root = assets_root()
        root.mkdir(parents=True, exist_ok=True)
        lock_file = root / "download.lock"
        if not claim(lock_file):
            return  # another pbi-agent process is downloading
        try:
            if binary_path() is None:
                archive = root / runtime.url.rsplit("/", 1)[-1]
                download(runtime, archive, lock_file)
                extract(archive, runtime_dir())
                archive.unlink(missing_ok=True)
            if not model_path().is_file():
                download(MODEL, model_path(), lock_file)
        finally:
            lock_file.unlink(missing_ok=True)
        _log.info("Local session titles are ready.")
    except Exception as exc:
        _log.warning("Local session titles unavailable: %s", exc)
    finally:
        _ensure_lock.release()


def clean_title(raw: str) -> str:
    lines = raw.replace(_END_MARKER, "").strip().splitlines()
    if not lines:
        return ""
    title = lines[0].strip().strip("\"'").rstrip(".").rstrip()
    return title[:MAX_TITLE_CHARS].rstrip()


def generate_title(text: str) -> str | None:
    """One-line summary of ``text``, or None when unavailable or on failure."""
    content = text.strip()[:MAX_INPUT_CHARS]
    binary = binary_path()
    if not content or binary is None or not is_ready():
        return None
    # Keep user text from being parsed as the model's control tokens.
    content = content.replace("<|", "< |")
    # ChatML + LFM BOS, as the model was trained. llama.cpp drops one trailing
    # newline from a prompt file, hence the doubled one.
    prompt = (
        "<|startoftext|><|im_start|>user\n"
        f"{content}<|im_end|>\n<|im_start|>assistant\n\n"
    )
    # Prompt evaluation on every logical CPU oversubscribes hyper-threaded and
    # virtualized hosts (measured: 3 s instead of 0.4 s), so use half of them.
    threads = str(max((os.cpu_count() or 2) // 2, 1))
    with tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", suffix=".txt", dir=assets_root(), delete=False
    ) as handle:
        handle.write(prompt)
    prompt_file = Path(handle.name)
    command = [
        str(binary),
        *("-m", str(model_path())),
        *("-f", str(prompt_file)),
        *("-n", str(_MAX_NEW_TOKENS)),
        *("-c", str(_CONTEXT_TOKENS)),
        *("-t", threads),
        *("-tb", threads),
        *("-b", "512"),
        *("--temp", "0"),
        # Flash attention changes this model's outputs.
        *("-fa", "off"),
        "-no-cnv",
        "--no-display-prompt",
        "--no-warmup",
        "--no-perf",
        "--simple-io",
        "--offline",
    ]
    try:
        with _generate_lock:
            completed = subprocess.run(
                command,
                check=False,
                capture_output=True,
                stdin=subprocess.DEVNULL,
                timeout=_GENERATE_TIMEOUT_SECS,
                encoding="utf-8",
                errors="replace",
                creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
            )
    except (OSError, subprocess.TimeoutExpired) as exc:
        _log.debug("Local title generation failed: %s", exc)
        return None
    finally:
        prompt_file.unlink(missing_ok=True)
    if completed.returncode != 0:
        _log.debug("llama-completion exited with %s", completed.returncode)
        return None
    return clean_title(completed.stdout) or None
